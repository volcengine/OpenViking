"""Private file handles for large Compile assignments and scoped tool results."""

from __future__ import annotations

import json
import uuid

from vikingbot.agent.tools.base import MultimodalToolResult


async def _store_text(sandbox, root, path, text, *, page_chars=512):
    """Save exact text and a bounded JSONL view when line-based reads cannot page it.

    JSONL text fields concatenate to the original text without inserted separators.
    File paths are generated by Compile and remain relative to the private child root.
    UTF-8 byte writes preserve line endings independently of the sandbox host.
    """
    await sandbox.write_file_bytes(f"{root}/{path}", text.encode("utf-8"))
    result = {"file": path}
    if any(len(line) > page_chars for line in text.splitlines()):
        pages = path + ".jsonl"
        content = "\n".join(
            json.dumps(
                {"offset": start, "text": text[start : start + page_chars]}, ensure_ascii=False
            )
            for start in range(0, len(text), page_chars)
        )
        await sandbox.write_file_bytes(f"{root}/{pages}", content.encode("utf-8"))
        result["pages"] = pages
    return result


async def prepare_assignment(data, sandbox, root):
    """Save assignment bodies behind private read handles without changing validator data.

    Input identities, evidence ranges, revisions and binary handles stay in the
    manifest. Derived payloads and text drafts remain complete in separate files.
    The returned manifest handle replaces only the model-facing initial assignment.
    """
    assignment = {k: v for k, v in data.items() if k != "original_evidence"}
    assignment["inputs"] = []

    async def body_view(value, name):
        """Externalize a text file body while retaining its path, revision and binary metadata."""
        if value.get("binary") or not isinstance(value.get("content"), str):
            return dict(value)
        handles = await _store_text(sandbox, root, name, value["content"])
        return {
            **{k: v for k, v in value.items() if k != "content"},
            **{f"content_{k}": v for k, v in handles.items()},
        }

    for index, item in enumerate(data.get("inputs", [])):
        value = dict(item)
        payload = item.get("payload", {})
        if payload.get("media_kind") != "image":
            handles = await _store_text(
                sandbox,
                root,
                f".inputs/input-{index}.json",
                json.dumps(payload, ensure_ascii=False, indent=2),
            )
            value["payload"] = {
                k: v
                for k, v in payload.items()
                if k in {"uri", "source_ranges", "evidence_spans", "media_kind"}
            }
            if "text" in payload and "uri" in payload:
                value["payload"]["source_ranges"] = [item["id"]]
            value.update({f"payload_{k}": v for k, v in handles.items()})
        if "ready_file" in item:
            value["ready_file"] = await body_view(item["ready_file"], f".inputs/ready-{index}.txt")
        assignment["inputs"].append(value)

    for key in ("historical_files", "candidates"):
        if key in data:
            assignment[key] = [
                await body_view(value, f".inputs/{key}-{index}.txt")
                for index, value in enumerate(data[key])
            ]
    await sandbox.write_file(
        f"{root}/.inputs/assignment.json", json.dumps(assignment, ensure_ascii=False, indent=2)
    )
    return {
        "assignment_file": ".inputs/assignment.json",
        "instructions": (
            "Read .inputs/assignment.json with read_file offset/limit. Read payload_file and content_file "
            "for complete assigned facts and drafts; source_ranges are also readable with read_evidence. "
            "For long lines, use payload_pages or content_pages: each JSONL line carries offset/text; "
            "read one line at a time and concatenate text fields without separators. "
            "Process all assigned inputs before submitting the complete result."
        ),
    }


def make_tool_result_preview(sandbox, root, max_chars):
    """Return a child-local spill adapter that bounds text while preserving native image blocks.

    max_chars bounds preview characters and must allow a complete retrieval handle.
    Spill failures propagate; callers never receive an inaccessible partial result.
    """
    if max_chars < 256:
        raise ValueError("Tool result previews require at least 256 characters")

    async def preview(result, session_key, *, preserve_complete=False):
        """Retain short results; return accessible full-text handles for oversized results."""
        multimodal = isinstance(result, MultimodalToolResult)
        content_text = (
            [part.get("text", "") for part in result.content if part.get("type") == "text"]
            if multimodal
            else []
        )
        text = str(result)
        if max(len(text), sum(map(len, content_text))) <= max_chars:
            return result
        complete = (
            json.dumps({"text": text, "content_text": content_text}, ensure_ascii=False, indent=2)
            if multimodal
            else text
        )
        handles = await _store_text(
            sandbox,
            root,
            f".inputs/tool-results/{uuid.uuid4().hex}.txt",
            complete,
            page_chars=max_chars // 8,
        )
        readable = handles.get("pages", handles["file"])
        notice = (
            f"Full result: {handles['file']}; read {readable} with offset/limit. "
            + ("JSONL text fields concatenate without separators. " if "pages" in handles else "")
            + "Preview:\n"
        )
        bounded = notice + text[: max(0, max_chars - len(notice))]
        if not multimodal:
            return bounded
        return MultimodalToolResult(
            text=bounded,
            content=[
                {"type": "text", "text": bounded},
                *[part for part in result.content if part.get("type") != "text"],
            ],
        )

    return preview
