import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const directory = new URL('./', import.meta.url);
const source = new URL('../../../../../../docs/images/agents/', directory);
const agentIds = [
  'codex',
  'claude-code',
  'doubao-work',
  'workbuddy',
  'trae',
  'cursor',
  'openclaw',
  'hermes',
  'opencode',
  'deepseek-harness',
  'deerflow',
  'pi',
  'zcode',
  'kimi-code',
];
const methodIds = ['mcp', 'cli', 'api', 'sdk'];

// 发布快照只包含本组件使用的文案，不包含远端加载地址或图片。
for (const locale of ['zh', 'en']) {
  const catalog = JSON.parse(
    readFileSync(new URL(`${locale}/index.json`, source), 'utf8'),
  );
  const content = {};
  const readMarkdown = (path) =>
    readFileSync(
      new URL(`${locale}/${path.split('/').at(-1)}`, source),
      'utf8',
    ).trim();
  for (const id of [...agentIds, ...methodIds]) {
    const item = [...catalog.agents, ...catalog.accessMethods].find(
      (entry) => entry.id === id,
    );
    const agentCli = catalog.accessMethods.find(
      (entry) => entry.id === 'agent-cli',
    );
    const tabs =
      id === 'cli'
        ? [
            {
              id: 'human',
              label:
                locale === 'zh'
                  ? '手动终端安装'
                  : 'Manual terminal installation',
              detailPath: item.detailPath,
            },
            {
              id: 'agent',
              label:
                locale === 'zh' ? '通过 AI Agent 安装' : 'Install via AI Agent',
              detailPath: agentCli.detailPath,
            },
          ]
        : (item.tabs ?? []);
    content[id === 'doubao-work' ? 'doubao' : id] = {
      name: item.name,
      description:
        id === 'cli'
          ? locale === 'zh'
            ? 'OpenViking CLI 支持开发者在终端直接安装、配置和使用，也可以把安装配置指令交给 AI Agent，让它像 skill 一样学会并记住 CLI 用法。'
            : 'OpenViking CLI supports direct installation, configuration and use in the terminal. You can also give the setup instructions to an AI Agent so it learns and remembers CLI usage like a skill.'
          : item.summary,
      tags: item.tags ?? [],
      markdown: readMarkdown(item.detailPath),
      guides: tabs.map((tab) => ({
        id: tab.id,
        label: tab.label,
        markdown: readMarkdown(tab.detailPath),
      })),
    };
  }
  writeFileSync(
    fileURLToPath(new URL(`content-${locale}.ts`, directory)),
    await format(
      `// Generated by generate-content.mjs from docs/images/agents/${locale}; do not edit.\nexport default ${JSON.stringify(content, null, 2)};\n`,
      { parser: 'typescript', singleQuote: true, trailingComma: 'all' },
    ),
  );
}
