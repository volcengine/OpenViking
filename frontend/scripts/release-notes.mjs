import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { groupChangelog, parseSummary } from './bilingual-changelog.mjs';

export function checkChangesets(root) {
  for (const file of readdirSync(join(root, '.changeset'))) {
    if (!file.endsWith('.md') || file === 'README.md') continue;
    const source = readFileSync(join(root, '.changeset', file), 'utf8');
    const match = source.match(
      /^---\r?\n((?:.*\r?\n)*?)---(?:\r?\n|$)([\s\S]*)$/,
    );
    if (!match) throw new Error(`${file}: missing changeset frontmatter`);
    // Changesets supports an empty file for changes that do not release a package.
    if (['', '{}'].includes(match[1].trim()) && !match[2].trim()) continue;
    parseSummary(match[2], file);
  }
}

export async function syncReleaseNotes(root, check = false) {
  checkChangesets(root);
  const source = readFileSync(
    join(root, 'packages/react/CHANGELOG.md'),
    'utf8',
  );
  const { version } = JSON.parse(
    readFileSync(join(root, 'packages/react/package.json'), 'utf8'),
  );
  // Beta publishing temporarily stages a version based on npm latest, which
  // can belong to an older major than the stable release prepared in Git.
  const docsVersion = version.includes('-')
    ? source.match(/^## (\d+\.\d+\.\d+)\s*$/m)?.[1]
    : version;
  if (!docsVersion) throw new Error('No stable release notes in CHANGELOG');
  for (const [language, locale, title, intro] of [
    [
      'en',
      'en-US',
      'Release notes',
      'Changes in stable releases of `@openviking/react`.',
    ],
    ['zh', 'zh-CN', '发布日志', '`@openviking/react` 稳定版本的变更记录。'],
  ]) {
    const path = join(root, `docs/docs/${language}/guide/changelog.md`);
    const sourcePage = `<!-- Generated by npm run sync:release-notes. -->\n\n# ${title}\n\n${intro}\n\n${groupChangelog(source, locale, docsVersion)}\n`;
    const content = await format(sourcePage, {
      ...(await resolveConfig(path)),
      parser: 'markdown',
    });
    if (check) {
      if (readFileSync(path, 'utf8') !== content) {
        throw new Error(`${path}: run npm run sync:release-notes`);
      }
    } else {
      writeFileSync(path, content);
    }
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  if (process.argv.includes('--changesets-only')) checkChangesets(root);
  else await syncReleaseNotes(root, process.argv.includes('--check'));
}
