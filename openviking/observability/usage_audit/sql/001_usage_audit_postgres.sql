-- Run once as a provisioning role. For a custom schema, replace every
-- openviking_usage_audit identifier before executing this script.
-- Runtime needs USAGE on schema, SELECT/INSERT/UPDATE/DELETE on tables,
-- and USAGE/SELECT on sequences; it does not need CREATE.
BEGIN;
CREATE SCHEMA openviking_usage_audit;

CREATE TABLE openviking_usage_audit._schema_meta (
    key text COLLATE "C" PRIMARY KEY,
    value text COLLATE "C" NOT NULL
);

CREATE TABLE openviking_usage_audit.usage_token_hourly (
    account_id text COLLATE "C" NOT NULL,
    user_id text COLLATE "C" NOT NULL,
    date_utc text COLLATE "C" NOT NULL,
    hour_utc integer NOT NULL CHECK (hour_utc BETWEEN 0 AND 23),
    source text COLLATE "C" NOT NULL,
    token_type text COLLATE "C" NOT NULL,
    provider text COLLATE "C" NOT NULL,
    model_name text COLLATE "C" NOT NULL,
    token_count bigint NOT NULL DEFAULT 0,
    updated_at text COLLATE "C" NOT NULL,
    PRIMARY KEY (account_id, user_id, date_utc, hour_utc, source, token_type, provider, model_name)
);
CREATE INDEX idx_usage_token_account_date
    ON openviking_usage_audit.usage_token_hourly(account_id, date_utc, hour_utc);

CREATE TABLE openviking_usage_audit.usage_retrieval_hourly (
    account_id text COLLATE "C" NOT NULL,
    user_id text COLLATE "C" NOT NULL,
    date_utc text COLLATE "C" NOT NULL,
    hour_utc integer NOT NULL CHECK (hour_utc BETWEEN 0 AND 23),
    operation text COLLATE "C" NOT NULL,
    status text COLLATE "C" NOT NULL,
    request_count bigint NOT NULL DEFAULT 0,
    result_count bigint NOT NULL DEFAULT 0,
    updated_at text COLLATE "C" NOT NULL,
    PRIMARY KEY (account_id, user_id, date_utc, hour_utc, operation, status)
);
CREATE INDEX idx_usage_retrieval_account_date
    ON openviking_usage_audit.usage_retrieval_hourly(account_id, date_utc, hour_utc);

CREATE TABLE openviking_usage_audit.usage_context_write_bucket (
    account_id text COLLATE "C" NOT NULL,
    user_id text COLLATE "C" NOT NULL,
    date_utc text COLLATE "C" NOT NULL,
    hour_utc integer NOT NULL CHECK (hour_utc BETWEEN 0 AND 23),
    operation text COLLATE "C" NOT NULL,
    count bigint NOT NULL DEFAULT 0,
    updated_at text COLLATE "C" NOT NULL,
    PRIMARY KEY (account_id, user_id, date_utc, hour_utc, operation)
);
CREATE INDEX idx_usage_context_write_account_date
    ON openviking_usage_audit.usage_context_write_bucket(account_id, date_utc, hour_utc);

CREATE TABLE openviking_usage_audit.request_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id text COLLATE "C",
    account_id text COLLATE "C" NOT NULL,
    user_id text COLLATE "C",
    method text COLLATE "C" NOT NULL,
    route text COLLATE "C" NOT NULL,
    api_type text COLLATE "C" NOT NULL,
    status_code integer NOT NULL,
    duration_ms double precision NOT NULL,
    error_code text COLLATE "C",
    error_message text COLLATE "C",
    error_details text COLLATE "C",
    created_at text COLLATE "C" NOT NULL
);
CREATE INDEX idx_request_audit_account_created
    ON openviking_usage_audit.request_audit(account_id, created_at DESC, id DESC);
CREATE INDEX idx_request_audit_account_id
    ON openviking_usage_audit.request_audit(account_id, id DESC);
CREATE INDEX idx_request_audit_request_id
    ON openviking_usage_audit.request_audit(request_id);
CREATE INDEX idx_request_audit_account_api
    ON openviking_usage_audit.request_audit(account_id, api_type);
CREATE INDEX idx_request_audit_account_status
    ON openviking_usage_audit.request_audit(account_id, status_code);
-- Fences survive projection deletion/retention and invalidate events admitted
-- by another writer before it observed the latest deletion generation.
CREATE TABLE openviking_usage_audit.usage_deletion_fence (
    account_id text COLLATE "C" NOT NULL,
    scope text COLLATE "C" NOT NULL CHECK (scope IN ('account', 'user')),
    user_id text COLLATE "C" NOT NULL,
    generation bigint NOT NULL CHECK (generation > 0),
    PRIMARY KEY (account_id, scope, user_id)
);
INSERT INTO openviking_usage_audit._schema_meta (key, value)
    VALUES ('version', '2'), ('deletion_generation', '0');
COMMIT;
